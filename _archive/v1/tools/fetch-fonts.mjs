// Self-hosts the Google Fonts used by the site (all SIL Open Font License) so no third-party CSS blocks first paint.
// Downloads the Latin subset as woff2 (variable fonts: one file covers every weight) into assets/fonts and writes css/fonts.css.
// Re-run any time with:  node tools/fetch-fonts.mjs
import { mkdir, writeFile } from 'node:fs/promises';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const sources = [
  { url: 'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,400;0,500;0,600;1,400;1,500&display=swap', weights: '400 600' },
  { url: 'https://fonts.googleapis.com/css2?family=Jost:wght@400;500&display=swap', weights: '400 500' },
  { url: 'https://fonts.googleapis.com/css2?family=Allura&text=Arifa&display=swap', weights: '400' } // "Arifa" glyphs only
];
await mkdir(new URL('../assets/fonts/', import.meta.url), { recursive: true });

const seen = new Set();
let css = '/* Self-hosted fonts (SIL OFL): Cormorant Garamond, Jost, Allura. Generated by tools/fetch-fonts.mjs */\n';
for (const { url: src, weights } of sources) {
  const text = await (await fetch(src, { headers: { 'User-Agent': UA } })).text();
  const faces = [...text.matchAll(/(?:\/\* ([\w-]+) \*\/\s*)?@font-face\s*\{([^}]+)\}/g)];
  for (const [, subset, body] of faces) {
    if (subset && subset !== 'latin') continue;
    const family = /font-family: '([^']+)'/.exec(body)[1];
    const style = /font-style: (\w+)/.exec(body)[1];
    const key = `${family}|${style}`;
    if (seen.has(key)) continue; // variable font: one file serves every weight
    seen.add(key);
    const file = `${family.replace(/\s+/g, '')}${style === 'italic' ? '-italic' : ''}.woff2`;
    const fontUrl = /url\((https:[^)]+)\)/.exec(body)[1];
    await writeFile(new URL(`../assets/fonts/${file}`, import.meta.url), Buffer.from(await (await fetch(fontUrl)).arrayBuffer()));
    const range = /unicode-range: ([^;]+);/.exec(body)?.[1];
    css += `@font-face { font-family: '${family}'; font-style: ${style}; font-weight: ${weights}; font-display: swap; src: url(../assets/fonts/${file}) format('woff2');${range ? ` unicode-range: ${range};` : ''} }\n`;
    console.log('saved', file);
  }
}
await writeFile(new URL('../css/fonts.css', import.meta.url), css);
console.log('wrote css/fonts.css');
